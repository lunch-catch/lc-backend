-- ----------------------------------------------------------------------------
-- impression_log  |  릴레이가 포기한 노출을 가른다 (#1205)
--   정산이 상한(adserving.impression.dispatch.max-attempts)만큼 실패로 돌려준 노출은 포기한 시각을 채운다
--   채워진 노출은 릴레이가 다시 읽지 않고 밀린 수와 대기 시간에서도 빠진다. 사람이 고친 뒤 비우면 다시 넘긴다
--   시도 횟수로 가르지 않는 것은 상한을 올릴 때 이미 포기한 노출이 다시 넘겨지지 않게 하려는 것이다
--   열은 끝에 더해 테이블을 복사하지 않는다(INSTANT). 기존 행은 고치지 않는다. 상한에 닿은 기존 행은 한 번 더 넘겨 본 뒤 채워진다
-- ----------------------------------------------------------------------------
ALTER TABLE impression_log
    ADD COLUMN dispatch_abandoned_at DATETIME(6) COMMENT '릴레이가 상한만큼 실패해 넘기기를 포기한 시각. NULL 이면 포기하지 않았다',
    ALGORITHM = INSTANT;
