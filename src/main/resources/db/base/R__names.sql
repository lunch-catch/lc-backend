-- 3. 쿠폰 회차와 피드 후보에 복사된 가게 이름과 대상 메뉴 이름
UPDATE coupon_event e
JOIN store s ON s.store_id = e.store_id
LEFT JOIN store_menu m ON m.store_menu_id = e.target_menu_id
SET e.store_name = s.name,
    e.target_menu_name = IF(e.target_menu_id IS NULL, e.target_menu_name, m.name)
WHERE e.campaign_id BETWEEN 10000001 AND 19999999;
UPDATE ad_candidate a
JOIN campaign c ON c.campaign_id = a.campaign_id
JOIN store s ON s.store_id = c.store_id
LEFT JOIN store_menu m ON m.store_menu_id = c.target_menu_id
SET a.store_name = s.name,
    a.discount_menu_name = IF(c.target_menu_id IS NULL, a.discount_menu_name, m.name)
WHERE a.campaign_id BETWEEN 10000001 AND 19999999;
